#!/usr/bin/env python3
"""Construct exact rational certificates for flat ΛCDM H(z) and generate Lean proofs.

Standard-library-only. The Python verifier is *not* a formal proof: its role is to
create and sanity-check candidate certificates. `generated/HzExample.lean` is
intended for kernel checking against Physlib's real-valued definition.
"""
from __future__ import annotations

import argparse
import json
from decimal import Decimal, localcontext
from fractions import Fraction
from math import isqrt
from pathlib import Path


SCHEMA = "physlib-hz-interval-v1"
MODEL_FIELDS = {
    "cosmology": "flat ΛCDM: Omega_Lambda = 1 - Omega_m, Omega_r = Omega_K = 0",
    "physical_units": "H0 and H(z) in km s^-1 Mpc^-1; z and Omega_m dimensionless",
    "source": "Physlib.Cosmology.FLRW.FriedmannEquation.reducedHubble",
    "certificate_rule": "0<=lower<=upper and lower^2<=h_squared<=upper^2",
}
ASSUMPTIONS = ("H0>0", "0<=Omega_m<=1", "z>=0", "matter+Lambda, flat geometry, radiation neglected")


def valid_precision(digits: object) -> bool:
    # bool is a subclass of int, but is not a JSON integer precision.
    return type(digits) is int and 0 <= digits <= 100


def fraction(value: str | int | Fraction) -> Fraction:
    return Fraction(value)


def as_str(q: Fraction) -> str:
    return str(q.numerator) if q.denominator == 1 else f"{q.numerator}/{q.denominator}"


def make_certificate(h0: Fraction, omega_m: Fraction, z: Fraction, digits: int) -> dict:
    if h0 <= 0:
        raise ValueError("H0 must be strictly positive")
    if not (0 <= omega_m <= 1):
        raise ValueError("require 0 <= Omega_m <= 1 (flat matter + Lambda)")
    if z < 0:
        raise ValueError("require z >= 0")
    if not valid_precision(digits):
        raise ValueError("digits must be between 0 and 100")
    radicand = (1 - omega_m) + omega_m * (1 + z) ** 3
    squared = h0 * h0 * radicand
    scale = 10**digits
    # floor(sqrt(squared) * scale), entirely by integer arithmetic
    k = isqrt(squared.numerator * scale**2 // squared.denominator)
    lower = Fraction(k, scale)
    upper = lower if lower * lower == squared else Fraction(k + 1, scale)
    result = {
        "schema": SCHEMA,
        **MODEL_FIELDS,
        "h0": as_str(h0),
        "omega_m": as_str(omega_m),
        "z": as_str(z),
        "decimal_digits": digits,
        "radicand": as_str(radicand),
        "h_squared": as_str(squared),
        "lower": as_str(lower),
        "upper": as_str(upper),
        "guaranteed_width_at_most": as_str(Fraction(1, scale)),
        "assumptions": list(ASSUMPTIONS),
    }
    verify_certificate(result)
    return result


def verify_certificate(c: dict) -> bool:
    if c.get("schema") != SCHEMA:
        raise ValueError("unsupported certificate schema")
    for field, expected in MODEL_FIELDS.items():
        if c.get(field) != expected:
            raise ValueError(f"incorrect certificate {field}")
    if c.get("assumptions") != list(ASSUMPTIONS):
        raise ValueError("incorrect certificate assumptions")
    h0, om, z = (fraction(c[key]) for key in ("h0", "omega_m", "z"))
    digits = c["decimal_digits"]
    if not valid_precision(digits):
        raise ValueError("bad decimal_digits")
    if not (h0 > 0 and 0 <= om <= 1 and z >= 0):
        raise ValueError("input assumptions do not hold")
    radicand = (1 - om) + om * (1 + z) ** 3
    squared = h0**2 * radicand
    lower, upper = fraction(c["lower"]), fraction(c["upper"])
    if fraction(c["radicand"]) != radicand:
        raise ValueError("tampered radicand")
    if fraction(c["h_squared"]) != squared:
        raise ValueError("tampered squared prediction")
    if not (0 <= lower <= upper):
        raise ValueError("bounds must be nonnegative and ordered")
    if not (lower**2 <= squared <= upper**2):
        raise ValueError("squared enclosure failed")
    if fraction(c["guaranteed_width_at_most"]) != Fraction(1, 10**digits):
        raise ValueError("tampered tolerance")
    if not upper - lower <= Fraction(1, 10**digits):
        raise ValueError("requested tolerance violated")
    return True


def lean_rat(q: Fraction) -> str:
    if q.denominator == 1:
        return f"({q.numerator} : ℝ)"
    return f"({q.numerator} / {q.denominator} : ℝ)"


def render_lean(c: dict) -> str:
    verify_certificate(c)
    h0, om, z, lo, hi = (lean_rat(fraction(c[key])) for key in ("h0", "omega_m", "z", "lower", "upper"))
    tol = lean_rat(fraction(c["guaranteed_width_at_most"]))
    squared = lean_rat(fraction(c["h_squared"]))
    return f'''import HzCertificate

/-!
Automatically generated by scripts/hz_cert.py from an exact rational certificate.
The correctness of the output is checked by Lean; the generator itself is untrusted.
Do not edit the certificate numbers without rerunning Lean.
-/

namespace HzExample

/-- The real-valued Physlib prediction has this exact rational square. -/
theorem certified_square :
    HzCertificate.modelH {h0} {om} {z} ^ 2 = {squared} := by
  rw [HzCertificate.modelH_sq {h0} {om} {z} (by norm_num) (by norm_num)] <;> norm_num

/-- For the supplied H₀, Ωm, z, Physlib's reducedHubble prediction is enclosed. -/
theorem certified_interval :
    {lo} ≤ HzCertificate.modelH {h0} {om} {z} ∧
    HzCertificate.modelH {h0} {om} {z} ≤ {hi} := by
  apply HzCertificate.modelH_bounds
  all_goals norm_num

/-- The certified interval's width is within the requested tolerance. -/
theorem certified_width :
    {hi} - {lo} ≤ {tol} := by
  norm_num

#print axioms certified_square
#print axioms certified_interval
#print axioms certified_width
end HzExample
'''


def decimal_estimate(c: dict) -> str:
    """Human readable only; the rigorous bounds are the exact rationals."""
    squared = fraction(c["h_squared"])
    with localcontext() as ctx:
        ctx.prec = 70
        return str((Decimal(squared.numerator) / Decimal(squared.denominator)).sqrt())


def cli() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--h0", default="70", help="rational H0, e.g. 70, 67.4 or 674/10")
    ap.add_argument("--omega-m", default="3/10", help="rational Omega_m")
    ap.add_argument("--z", default="1", help="rational nonnegative redshift")
    ap.add_argument("--digits", type=int, default=8, help="interval width <= 10^(-digits)")
    ap.add_argument("--certificate", type=Path, help="output JSON path")
    ap.add_argument("--lean", type=Path, help="output Lean proof path")
    ap.add_argument("--verify", type=Path, help="verify an existing JSON certificate, no generation")
    args = ap.parse_args()
    if args.verify:
        data = json.loads(args.verify.read_text(encoding="utf-8"))
        verify_certificate(data)
        print("Exact-rational verification: PASSED")
        return
    cert = make_certificate(fraction(args.h0), fraction(args.omega_m), fraction(args.z), args.digits)
    if args.certificate:
        args.certificate.parent.mkdir(parents=True, exist_ok=True)
        args.certificate.write_text(json.dumps(cert, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    if args.lean:
        args.lean.parent.mkdir(parents=True, exist_ok=True)
        args.lean.write_text(render_lean(cert), encoding="utf-8")
    print(f"H(z) ≈ {decimal_estimate(cert)} km s^-1 Mpc^-1")
    print(f"Guaranteed exact rational enclosure: [{cert['lower']}, {cert['upper']}]")
    print(f"H(z)^2 = {cert['h_squared']} exactly")
    print("Exact-rational certificate verification: PASSED")
    print("Lean kernel verification: requires `lake build` (not run by this script)")


if __name__ == "__main__":
    cli()
